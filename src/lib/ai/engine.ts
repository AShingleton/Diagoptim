/**
 * Generic chat function for free-form AI interactions.
 * Supports custom system prompts, message history, and generation options.
 */
export async function chat(
  systemPrompt: string,
  messages: Message[],
  options?: ChatOptions
): Promise<string> {
  const temperature = options?.temperature ?? 0.5;
  const maxTokens = options?.maxTokens ?? DEFAULT_MAX_TOKENS;
  const stopSequences = options?.stopSequences;

  const anthropicMessages: Anthropic.MessageParam[] = messages.map((m) => ({
    role: m.role,
    content: m.content,
  }));

  const response = await callWithRetry(systemPrompt, anthropicMessages, {
    temperature,
    maxTokens,
    stopSequences,
  });

  return extractText(response);
}

