/**
 * Generates the next diagnostic question based on the current context.
 * Returns a structured question object ready for UI rendering.
 */
export async function generateDiagnosticQuestion(
  context: DiagnosticContext
): Promise<GeneratedQuestion> {
  // Dynamically import the prompt builder
  const { buildDiagnosticPrompt } = await import("./prompts/diagnostic");

  const systemPrompt = buildDiagnosticPrompt(context);

  const userMessage =
    context.previousAnswers.length === 0
      ? "Commence le diagnostic. Pose la premiere question."
      : `Voici la derniere reponse: ${JSON.stringify(
          context.previousAnswers[context.previousAnswers.length - 1]
        )}. Pose la question suivante.`;

  const response = await callWithRetry(
    systemPrompt,
    [{ role: "user", content: userMessage }],
    { temperature: 0.4, maxTokens: 2_048 }
  );

  const text = extractText(response);
  return parseJSON<GeneratedQuestion>(text);
}

/**
 * Analyzes an uploaded document and extracts structured data.
 * @param content - The text content of the document (from OCR or direct extraction).
 * @param type - The type of document being analyzed.
 */
export async function analyzeDocument(
  content: string,
  type: DocumentType
): Promise<ExtractedData> {
  const { getDocumentAnalysisPrompt } = await import(
    "./prompts/document-analysis"
  );

  const systemPrompt = getDocumentAnalysisPrompt(type);

  const response = await callWithRetry(
    systemPrompt,
    [
      {
        role: "user",
        content: `Analyse le document suivant et extrais les donnees structurees:\n\n${content}`,
      },
    ],
    { temperature: 0.1, maxTokens: 4_096 }
  );

  const text = extractText(response);
  return parseJSON<ExtractedData>(text);
}

/**
 * Generates prioritized recommendations based on full diagnostic data.
 * Recommendations include financial impact estimates and implementation steps.
 */
export async function generateRecommendations(
  diagnosticData: DiagnosticData
): Promise<Recommendation[]> {
  const { buildRecommendationsPrompt } = await import(
    "./prompts/recommendations"
  );

  const systemPrompt = buildRecommendationsPrompt();

  const response = await callWithRetry(
    systemPrompt,
    [
      {
        role: "user",
        content: JSON.stringify(diagnosticData),
      },
    ],
    { temperature: 0.3, maxTokens: 8_192 }
  );

  const text = extractText(response);
  return parseJSON<Recommendation[]>(text);
}

/**
 * Generates a high-level insight summary from the current answers and company profile.
 * Used to display real-time feedback during the diagnostic conversation.
 */
export async function generateInsight(
  answers: DiagnosticAnswer[],
  companyProfile: CompanyProfile
): Promise<string> {
  const systemPrompt = `Tu es un consultant expert en Lean Management et Six Sigma pour DiagOptim.
A partir des reponses du diagnostic et du profil de l'entreprise, genere un insight court et actionnable (2-3 phrases max).
L'insight doit etre encourageant et orienter vers une piste d'amelioration concrete.
Reponds uniquement avec le texte de l'insight, sans formatage JSON.`;

  const response = await callWithRetry(
    systemPrompt,
    [
      {
        role: "user",
        content: JSON.stringify({ answers, companyProfile }),
      },
    ],
    { temperature: 0.5, maxTokens: 512 }
  );

  return extractText(response);
}

