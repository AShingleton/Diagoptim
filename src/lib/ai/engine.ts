let clientSingleton: Anthropic | null = null;

/**
 * Creates (or returns the cached) Anthropic client.
 * Reads `ANTHROPIC_API_KEY` from `process.env`.
 */
export function createClient(): Anthropic {
  if (clientSingleton) return clientSingleton;

  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) {
    throw new Error(
      "Missing ANTHROPIC_API_KEY environment variable. " +
        "Set it in your .env.local file."
    );
  }

  clientSingleton = new Anthropic({ apiKey });
  return clientSingleton;
}

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

function recordUsage(
  response: Anthropic.Message
): void {
  usageLog.push({
    inputTokens: response.usage.input_tokens,
    outputTokens: response.usage.output_tokens,
    totalTokens: response.usage.input_tokens + response.usage.output_tokens,
    model: response.model,
    timestamp: new Date().toISOString(),
  });
}

/**
 * Calls the Anthropic API with automatic retries and exponential backoff.
 * @throws after MAX_RETRIES failures.
 */
async function callWithRetry(
  systemPrompt: string,
  messages: Anthropic.MessageParam[],
  options: { temperature: number; maxTokens: number; stopSequences?: string[] }
): Promise<Anthropic.Message> {
  const client = createClient();
  let lastError: unknown;

  for (let attempt = 1; attempt <= MAX_RETRIES; attempt++) {
    try {
      const response = await client.messages.create({
        model: MODEL,
        max_tokens: options.maxTokens,
        temperature: options.temperature,
        system: systemPrompt,
        messages,
        ...(options.stopSequences && options.stopSequences.length > 0
          ? { stop_sequences: options.stopSequences }
          : {}),
      });
      recordUsage(response);
      return response;
    } catch (error: unknown) {
      lastError = error;
      const isRetryable =
        error instanceof Anthropic.RateLimitError ||
        error instanceof Anthropic.InternalServerError ||
        error instanceof Anthropic.APIConnectionError;

      if (!isRetryable || attempt === MAX_RETRIES) {
        throw error;
      }

      const delay = BASE_DELAY_MS * Math.pow(2, attempt - 1);
      await new Promise((resolve) => setTimeout(resolve, delay));
    }
  }

  throw lastError;
}

/**
 * Extracts the text content from an Anthropic message response.
 */
function extractText(response: Anthropic.Message): string {
  const textBlock = response.content.find((b) => b.type === "text");
  if (!textBlock || textBlock.type !== "text") {
    throw new Error("No text content in AI response.");
  }
  return textBlock.text;
}

/**
 * Parses a JSON string from the AI response, stripping markdown fences if present.
 */
export function parseJSON<T>(raw: string): T {
  const cleaned = raw
    .replace(/^```(?:json)?\s*/i, "")
    .replace(/\s*```$/i, "")
    .trim();
  return JSON.parse(cleaned) as T;
}

